// Square icon-only button.
export function IconButton({ label, onClick, disabled = false, children, className = '' }) {
  return (
    <button
      type="button"
      className={`icon-button ${className}`}
      aria-label={label}
      title={label}
      onClick={onClick}
      disabled={disabled}
    >
      {children}
    </button>
  );
}
